// Local development commands. Never run against a shared database: both
// commands refuse unless APP_ENV is "local".
//
//   node src/local.ts setup   migrate, seed the demo workspace, issue a glasses token
//   node src/local.ts order   queue a test order without Telegram
//   node src/local.ts bind    print a one-time code to bind a Telegram group
//
// The demo catalogue is synthetic: made-up SKUs with made-up bins.

import { randomBytes } from "node:crypto";
import { access, copyFile, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import pg from "pg";
import { migrate } from "./db/migrate.ts";
import { createOrder } from "./fulfilment.ts";
import { hashToken } from "./http.ts";
import { hashCode } from "./telegram.ts";

const repoRoot = join(import.meta.dirname, "../../..");
const envFile = join(repoRoot, ".env.local");
const glassesEnvFile = join(repoRoot, "apps/glasses/.env.local");
const demoName = "Local demo stockroom";

const catalogue = [
  { sku: "TS-BLK-M", name: "Black T-shirt (M)", bin: "A-03", rank: 1 },
  { sku: "CP-WHT", name: "White cap", bin: "B-11", rank: 2 },
  { sku: "TB-NAT", name: "Natural tote bag", bin: "C-02", rank: 3 },
];

async function ensureEnvFile(): Promise<void> {
  try {
    await access(envFile);
  } catch {
    await copyFile(join(repoRoot, ".env.example"), envFile);
    const text = await readFile(envFile, "utf8");
    const secret = randomBytes(48).toString("base64url");
    await writeFile(envFile, text.replace(/^TASK_TOKEN_SECRET=$/m, `TASK_TOKEN_SECRET=${secret}`));
    console.log("created .env.local from .env.example with a fresh TASK_TOKEN_SECRET");
  }
  process.loadEnvFile(envFile);
  if (process.env.APP_ENV !== "local") throw new Error(`refusing to run: APP_ENV is ${process.env.APP_ENV ?? "unset"}, not local`);
}

async function demoWorkspace(client: pg.ClientBase): Promise<{ workspaceId: string; ownerId: string; pickerId: string }> {
  const existing = await client.query<{ id: string }>("select id from workspaces where name = $1", [demoName]);
  const workspaceId =
    existing.rows[0]?.id ?? (await client.query<{ id: string }>("insert into workspaces (name) values ($1) returning id", [demoName])).rows[0]!.id;
  const member = async (name: string, role: string) => {
    const found = await client.query<{ id: string }>("select id from members where workspace_id = $1 and display_name = $2", [workspaceId, name]);
    if (found.rows[0]) return found.rows[0].id;
    const made = await client.query<{ id: string }>(
      "insert into members (workspace_id, display_name, role) values ($1, $2, $3) returning id",
      [workspaceId, name, role],
    );
    return made.rows[0]!.id;
  };
  const ownerId = await member("Owner", "OWNER");
  const pickerId = await member("Picker 02", "PICKER");
  for (const product of catalogue) {
    await client.query(
      `insert into products (workspace_id, sku, normalized_sku, name, bin, route_rank) values ($1, $2, $2, $3, $4, $5)
       on conflict (workspace_id, normalized_sku) do nothing`,
      [workspaceId, product.sku, product.name, product.bin, product.rank],
    );
  }
  return { workspaceId, ownerId, pickerId };
}

async function setup(client: pg.ClientBase): Promise<void> {
  const applied = await migrate(client);
  const { workspaceId, pickerId } = await demoWorkspace(client);

  // A fresh token on every run; older local tokens for this picker stop working.
  await client.query("update device_tokens set revoked_at = now() where member_id = $1 and revoked_at is null", [pickerId]);
  const token = randomBytes(32).toString("base64url");
  await client.query(
    "insert into device_tokens (workspace_id, member_id, label, token_hash, expires_at) values ($1, $2, 'Local simulator', $3, now() + interval '30 days')",
    [workspaceId, pickerId, hashToken(token)],
  );
  const apiUrl = `http://localhost:${process.env.PORT ?? "8787"}`;
  await writeFile(
    glassesEnvFile,
    `# Generated by pnpm setup:local. Local only; do not commit.\nVITE_STOW_API_URL=${apiUrl}\nVITE_STOW_WORKSPACE_ID=${workspaceId}\nVITE_STOW_DEV_DEVICE_TOKEN=${token}\n`,
  );
  console.log(JSON.stringify({ msg: "local setup done", migrations: applied, workspaceId, glassesEnv: "apps/glasses/.env.local" }));
}

async function testOrder(client: pg.ClientBase, pool: pg.Pool): Promise<void> {
  const { workspaceId, ownerId } = await demoWorkspace(client);
  const created = await createOrder(pool, {
    workspaceId,
    createdBy: ownerId,
    sourceKey: `local:${randomBytes(8).toString("hex")}`,
    connectionId: null,
    sourceMessageId: null,
    request: { ref: null, lines: [{ sku: "TS-BLK-M", quantity: 3 }, { sku: "CP-WHT", quantity: 2 }, { sku: "TB-NAT", quantity: 1 }] },
  });
  console.log(JSON.stringify({ msg: "local test order queued", ...created }));
}

// The code goes to the owner, so sending it in a group links the owner's
// Telegram account as the coordinator for that group.
async function bindCode(client: pg.ClientBase): Promise<void> {
  const { workspaceId, ownerId } = await demoWorkspace(client);
  const code = randomBytes(5).toString("hex").toUpperCase();
  await client.query(
    "insert into telegram_bind_challenges (workspace_id, member_id, code_hash, expires_at) values ($1, $2, $3, now() + interval '10 minutes')",
    [workspaceId, ownerId, hashCode(code)],
  );
  console.log(`Send this in your test group within 10 minutes:\n\n/stow_bind ${code}\n`);
}

const command = process.argv[2];
if (command !== "setup" && command !== "order" && command !== "bind") throw new Error("usage: node src/local.ts setup|order|bind");
await ensureEnvFile();
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 2 });
const client = await pool.connect();
try {
  if (command === "setup") await setup(client);
  else if (command === "bind") await bindCode(client);
  else await testOrder(client, pool);
} finally {
  client.release();
  await pool.end();
}
